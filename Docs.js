// LIBRARY vs FRAMEWORK

// Library:
// - A collection of reusable code/functions.
// - Developer controls the application flow.
// - Developer calls the library when needed.
// - Example: React.

// Framework:
// - Provides a complete structure for building applications.
// - Framework controls much of the application flow.
// - Developer writes code according to the framework's conventions.
// - Example: Next.js.

// Easy rule:
// Library → You call it.
// Framework → It calls you.


// NEXT.JS

// Next.js is a React framework used to build modern
// full-stack web applications.

// Next.js is built on top of React.

// It provides features such as:
// - File-based routing
// - Server Components
// - Client Components
// - Server-side rendering
// - Data fetching
// - Route Handlers
// - Image optimization
// - Metadata/SEO
// - Loading and error handling

// React → UI library
// Next.js → React framework

// Easy definition:
// Next.js = React + additional features and
// structure for building complete web applications.

